export type Repo = {
  id: string; name: string; url: string; commit_sha: string;
  status: string; created_at?: string | null;
  counts: Partial<Record<'chunks'|'symbols'|'edges'|'dependencies'|'files',number>>;
};
export type Overview = {id:string;url:string;commit_sha:string;status:string;
  counts:Record<string,number>;edge_types:Record<string,number>;
  languages:Record<string,number>;has_exact_sources:boolean};
export type RepoFile={path:string;bytes:number|null;exact:boolean;chunks:number};
export type FileResponse={path:string;content:string;partial:boolean;lines:number;byte_count:number|null;note?:string};
export type CodeSymbol={id:string;name:string;qualified_name:string;kind:string;language?:string;
  file_path?:string;start_line:number;end_line:number};
export type GraphNode={id:string;label:string;file_path:string;kind:string;language:string;
  start_line?:number;end_line?:number};
export type GraphEdge={id:string;source:string;target:string|null;target_name:string;
  kind:string;line:number;resolved:boolean};
export type GraphData={nodes:GraphNode[];edges:GraphEdge[]};
export type Dependency={name:string;spec:string;manifest:string;group:string};
export type Source={label:string;file_path:string;symbol_name:string|null;
  start_line:number;end_line:number;distance?:number|null;origin?:string;
  channels?:string[];fusion_score?:number|null;rerank_score?:number|null};
export type DocSource={label:string;library:string;topic:string;title:string;url:string};
export type Answer={answer:string;status:string;cached:boolean;trace_id?:string|null;
  sources:Source[];docs_sources:DocSource[];trace:string[];limitations?:string[];
  verified_labels?:string[];verification_scope?:string};
export type Job={id:string;kind:string;status:'queued'|'running'|'complete'|'failed';
  stage:string;percent:number;detail:string;error?:string|null;
  result?:{repo_id?:string;count?:number;results?:EvalCase[]}|null;
  events:{stage:string;percent:number;detail:string;time:number}[]};
